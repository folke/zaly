// oxlint-disable no-await-in-loop
import { Ajv } from "ajv"
import standalone from "ajv/dist/standalone/index.js"
import { globSync, mkdirSync, writeFileSync } from "node:fs"
import { basename, dirname, join } from "pathe"
import { generateSchema } from "ts-json-schema-generator"
import { normalizeSchema } from "./schemas-normalize.ts"
import { enrichThemeSchema } from "./schemas-theme.ts"

export type SchemaSource = {
  path: string
  type: string
  enrich?: "theme"
  functions?: "fail" | "hide" | "comment"
}

async function schemaFromType(root: string, source: SchemaSource) {
  const schema = await generateSchema({
    functions: source.functions,
    path: join(root, source.path),
    topRef: false,
    tsconfig: join(root, "tsconfig.json"),
    type: source.type,
  })
  switch (source.enrich) {
    case "theme": {
      return enrichThemeSchema(schema)
    }
    case undefined: {
      return normalizeSchema(schema)
    }
    default: {
      throw new Error("Unknown schema enrichment")
    }
  }
}

function moduleCode(code: string, name: string) {
  return `// Generated by @zaly/dev. Do not edit.
// @ts-nocheck
interface ValidationError {
  instancePath: string
  keyword: string
  message?: string
  params: Record<string, unknown>
}
interface Checker {
  (input: unknown): boolean
  errors?: ValidationError[] | null
}
const validator: Checker = (() => {
  const module = { exports: {} as { default: Checker } }
${code}
  return module.exports.default
})()

export function check(input: unknown): boolean {
  return validator(input)
}

export function validate(input: unknown): unknown {
  if (check(input)) return input
  const errors = (validator.errors ?? []).map((error) => {
    let path = error.instancePath
    if (error.keyword === "required") path += "/" + String(error.params.missingProperty)
    if (error.keyword === "additionalProperties") path += "/" + String(error.params.additionalProperty)
    return (path === "" ? "/" : path) + ": " + (error.message ?? error.keyword)
  })
  throw new Error(${JSON.stringify(`Invalid ${name}:\n`)} + errors.join("\\n"))
}
`
}

export async function generateSchemas(root: string) {
  for (const file of globSync(join(root, "src/schemas/tpl/*.ts")).toSorted()) {
    const template = await import(file)
    if (template.source && template.schema)
      throw new Error(`Schema template must export either source or schema, not both: ${file}`)
    const schema = template.source ? await schemaFromType(root, template.source) : template.schema
    if (!schema || typeof schema !== "object") throw new Error(`Missing schema source: ${file}`)
    const name = basename(file, ".ts")
    const output = join(root, "src/schemas/gen", `${name}.ts`)
    if (schema.$async) throw new Error(`Async standalone validators are not supported: ${file}`)
    const json = JSON.stringify(schema, undefined, 2)
    const ajv = new Ajv({
      allErrors: true,
      code: { esm: true, source: true },
      inlineRefs: false,
      strict: true,
    })
    const validate = ajv.compile(JSON.parse(json))
    const source = standalone.default(ajv, validate)
    const bundle = await Bun.build({
      entrypoints: ["validator.mjs"],
      format: "cjs",
      plugins: [
        {
          name: "standalone-validator",
          setup(build) {
            build.onResolve({ filter: /^validator\.mjs$/ }, () => ({
              namespace: "validator",
              path: "validator.mjs",
            }))
            build.onResolve({ filter: /^ajv\// }, ({ path }) => ({
              namespace: "file",
              path: Bun.resolveSync(path, import.meta.dirname),
            }))
            build.onLoad({ filter: /.*/, namespace: "validator" }, () => ({
              contents: source,
              loader: "js",
            }))
          },
        },
      ],
      target: "node",
    })
    if (!bundle.success) throw new AggregateError(bundle.logs, `Failed to bundle ${file}`)
    if (bundle.outputs.length !== 1)
      throw new Error(`Expected a single standalone validator for ${file}`)
    mkdirSync(dirname(output), { recursive: true })
    mkdirSync(join(root, "assets/schemas"), { recursive: true })
    writeFileSync(join(root, "assets/schemas", `${name}.schema.json`), `${json}\n`)
    writeFileSync(output, moduleCode(await bundle.outputs[0]!.text(), name))
    console.log(`✔  ${name}: JSON Schema + standalone validator`)
  }
}
